def today_kst():
    return datetime.now(KST).date()


def _rng(*parts):
    seed = hashlib.sha256("|".join(str(p) for p in parts).encode()).hexdigest()
    return random.Random(int(seed[:16], 16))


def zodiac_info(key):
    return next((z for z in ZODIAC if z[0] == key), None)


def daily_love(sign, day=None):
    """별자리의 오늘 연애운. 같은 날·같은 별자리면 항상 같은 결과."""
    z = zodiac_info(sign)
    if not z:
        return None
    day = day or today_kst()
    r = _rng("love", day.isoformat(), sign)
    score = r.choices([5, 4, 3, 2, 1], weights=[22, 32, 26, 13, 7])[0]
    color = r.choice(COLORS)
    match = r.choice([x for x in ZODIAC if x[0] != sign])
    place = r.choice([p for p in PLACES if p["cat"] in ("date", "cafe", "activity")])
    return {
        "key": z[0], "name": z[1], "emoji": z[2], "period": z[3],
        "score": score,
        "message": r.choice(MESSAGES[score]),
        "advice": r.choice(ADVICE),
        "color_name": color[0], "color_hex": color[1],
        "item": r.choice(ITEMS),
        "number": r.randint(1, 9),
        "match": match,
        "place": place,
    }


def ranking(day=None):
    """오늘의 별자리 연애운 순위 (점수 높은 순)."""
    day = day or today_kst()
    rows = [daily_love(z[0], day) for z in ZODIAC]
    return sorted(rows, key=lambda x: -x["score"])


