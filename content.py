# 인지기능 이론에서 자주 언급되는 '천생연분' 조합(듀얼)
GOLDEN_PAIRS = {
    frozenset({"INFP", "ENFJ"}),
    frozenset({"INTP", "ENTJ"}),
    frozenset({"INFJ", "ENTP"}),
    frozenset({"INTJ", "ENFP"}),
    frozenset({"ISFP", "ESFJ"}),
    frozenset({"ISTP", "ESTJ"}),
    frozenset({"ISFJ", "ESFP"}),
    frozenset({"ISTJ", "ESTP"}),
}

MBTI_TYPES = list(MBTI_INFO.keys())


def mbti_compatibility(a, b):
    """두 MBTI의 궁합을 점수(0-100)·등급·설명으로 반환."""
    a = (a or "").upper().strip()
    b = (b or "").upper().strip()
    if a not in MBTI_INFO or b not in MBTI_INFO:
        return None

    if frozenset({a, b}) in GOLDEN_PAIRS:
        score = 96
    else:
        shared = sum(1 for i in range(4) if a[i] == b[i])
        # 같은 글자가 많을수록 편안하지만, 너무 똑같아도 밋밋할 수 있음
        base = {0: 62, 1: 70, 2: 78, 3: 84, 4: 80}[shared]
        score = base

    parts = []
    # 에너지 방향(E/I)
    if a[0] != b[0]:
        parts.append("한 명은 활발하고 한 명은 차분해, 서로의 에너지를 채워줘요.")
    else:
        parts.append("함께 있는 시간과 혼자만의 시간에 대한 감각이 비슷해요.")
    # 인식 방식(N/S)
    if a[1] == b[1]:
        parts.append("세상을 보는 방식이 닮아 대화가 잘 통합니다.")
    else:
        parts.append("현실 감각과 상상력이 서로를 보완해줘요.")
    # 판단 방식(T/F)
    if a[2] == b[2]:
        parts.append("결정을 내리는 기준이 비슷해 갈등이 적어요.")
    else:
        parts.append("이성과 감성이 균형을 이뤄, 서로에게 배울 점이 많아요.")
    # 생활 방식(J/P)
    if a[3] != b[3]:
        parts.append("계획형과 즉흥형이 만나 일상이 유연해져요.")

    if score >= 90:
        grade = "천생연분"
    elif score >= 78:
        grade = "아주 좋아요"
    elif score >= 70:
        grade = "잘 맞아요"
    else:
        grade = "노력하면 충분히"

    return {"a": a, "b": b, "score": score, "grade": grade,
            "comment": " ".join(parts)}
