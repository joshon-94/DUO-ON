def get_trips(length=None, region=None):
    items = TRIPS
    if length and length in {k for k, _ in LENGTHS}:
        items = [t for t in items if t["length"] == length]
    if region:
        items = [t for t in items if t["region"] == region]
    return items


def get_trip(trip_id):
    return next((t for t in TRIPS if t["id"] == trip_id), None)


