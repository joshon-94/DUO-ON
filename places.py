def get_places(region=None, cat=None, indoor=False, sub=None):
    """지역/카테고리/세부 분류(/실내 여부)로 필터링한 장소 목록."""
    items = PLACES
    if region and region in REGIONS:
        items = [p for p in items if p["region"] == region]
    if cat and cat in {c[0] for c in CATEGORIES}:
        items = [p for p in items if p["cat"] == cat]
        if sub and sub in {s[0] for s in SUBS.get(cat, [])}:
            items = [p for p in items if p.get("sub") == sub]
    if indoor:
        items = [p for p in items if p.get("indoor")]
    return items


def category_label(key):
    for k, label, emoji, _ in CATEGORIES:
        if k == key:
            return emoji, label
    return "", ""
